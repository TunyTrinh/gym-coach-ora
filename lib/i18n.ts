export const LANGUAGE_STORAGE_KEY = "gymflow_language_pref";

export async function getStoredLanguage(): Promise<LanguageCode> {
  try {
    const value = await AsyncStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (value === "vi" || value === "en") return value;
  } catch {
    // Keep English as a safe fallback when storage is unavailable.
  }
  return "en";
}

export async function setStoredLanguage(language: LanguageCode): Promise<void> {
  try {
    await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // The in-memory provider still applies the change immediately.
  }
}

export function localeFor(language: LanguageCode): string {
  return language === "vi" ? "vi-VN" : "en-US";
}

export function formatDateLocalized(dateInput: string | Date, language: LanguageCode, options?: Intl.DateTimeFormatOptions): string {
  const date = new Date(dateInput);
  if (Number.isNaN(date.getTime())) return String(dateInput);
  return new Intl.DateTimeFormat(localeFor(language), options ?? { weekday: "short", month: "short", day: "numeric", year: "numeric" }).format(date);
}

export function formatTimeLocalized(dateInput: string | Date, language: LanguageCode): string {
  const date = new Date(dateInput);
  if (Number.isNaN(date.getTime())) return String(dateInput);
  return new Intl.DateTimeFormat(localeFor(language), { hour: "numeric", minute: "2-digit" }).format(date);
}
